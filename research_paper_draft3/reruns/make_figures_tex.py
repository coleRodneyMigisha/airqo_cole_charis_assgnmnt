"""Write the pgfplots code for the two new figures and render PNG copies for the docx.

Usage: python -I make_figures_tex.py   (from the repository root)

Reads   research_paper_ieee/figures/data/fig_eda_*.csv, fig_obspred_*.csv and their *_meta.csv
Writes  research_paper_ieee/figures/fig_eda.tex, fig_obspred.tex  (\\input by main.tex)
        research_paper_draft3/figures/fig_eda.png, fig_obspred.png (for make_docx.py)
Style follows main.tex: PANTONE 3015 C blue (pblue), its tints and grey only.
"""
import csv
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path.cwd()
FIG = ROOT / 'research_paper_ieee' / 'figures'
DATA = FIG / 'data'
DOCX_FIG = ROOT / 'research_paper_draft3' / 'figures'


def rows(name):
    with open(DATA / name, newline='') as handle:
        return list(csv.DictReader(handle))


def tex_escape(text):
    return text.replace('&', '\\&').replace('_', '\\_').replace('%', '\\%')


# ---------------------------------------------------------------- EDA, 2 x 2
meta = rows('fig_eda_meta.csv')
bursts = rows('fig_eda_bursts.csv')
n_hours = len(rows('fig_eda_1.csv'))
ymax = 0.0
for k in range(1, 5):
    for r in rows(f'fig_eda_{k}.csv'):
        for key in ('pm25', 'pm25_raw'):
            if r[key] not in ('', 'nan'):
                ymax = max(ymax, float(r[key]))
ymax = min(ymax * 1.05, 450)
separators = ''.join(
    f'\\draw[black!35, densely dotted] (axis cs:{int(b["start"]) - 0.5},0) -- (axis cs:{int(b["start"]) - 0.5},{ymax:.0f});'
    for b in bursts[1:])
burst_ticks = ','.join(str(int(b['start'])) for b in bursts)
burst_labels = ','.join(b['label'] for b in bursts)
panels = []
for m in meta:
    k = m['panel']
    site = 'Sensor ' + tex_escape(m['device'])
    title = f'{site}: {m["data_class"]}, {float(m["offline_pct"]):.0f}\\% offline'
    panels.append(
        f"\\nextgroupplot[title={{{title}}}]\n"
        f"\\addplot[black!40, line width=0.5pt, densely dashed] table[x=h, y=pm25_raw, col sep=comma] {{figures/data/fig_eda_{k}.csv}};\n"
        f"\\addplot[pbluedark, line width=0.8pt] table[x=h, y=pm25, col sep=comma] {{figures/data/fig_eda_{k}.csv}};\n"
        f"{separators}\n")
eda = (
    "% Generated by research_paper_draft3/reruns/make_figures_tex.py from review_extras (train.ipynb rerun).\n"
    "\\begin{tikzpicture}\n"
    "\\begin{groupplot}[group style={group size=2 by 2, horizontal sep=10mm, vertical sep=14mm},\n"
    f"  width=0.5\\textwidth, height=38mm, xmin=-0.5, xmax={n_hours - 0.5}, ymin=0, ymax={ymax:.0f},\n"
    f"  xtick={{{burst_ticks}}}, xticklabels={{{burst_labels}}},\n"
    "  xlabel={Observation hours, in three bursts}, ylabel={PM2.5 (\\ugm)}, label style={font=\\scriptsize}, tick label style={font=\\scriptsize},\n"
    "  title style={font=\\scriptsize\\bfseries, text=pbluedark}, ymajorgrids, grid style={black!15},\n"
    "  axis x line*=bottom, axis y line*=left, unbounded coords=jump]\n"
    + ''.join(panels) +
    "\\end{groupplot}\n\\end{tikzpicture}\n")
(FIG / 'fig_eda.tex').write_text(eda)

# ------------------------------------------------- observed against predicted
meta = rows('fig_obspred_meta.csv')
ymax = 0.0
for k in (1, 2):
    for r in rows(f'fig_obspred_{k}.csv'):
        for key in ('obs', 'persist', 'svr', 'lgbh'):
            if r[key] not in ('', 'nan'):
                ymax = max(ymax, float(r[key]))
ymax = ymax * 1.05
panels = []
for m in meta:
    k = m['panel']
    title = (f'Sensor {tex_escape(m["device"])} ({m["data_class"]}), '
             f'{m["start"][8:]}--{m["end"][8:]} August 2026')
    legend = ("legend to name=oplegend, legend columns=4, legend style={font=\\scriptsize, draw=none, "
              "/tikz/every even column/.append style={column sep=6pt}}, " if k == '1' else '')
    panels.append(
        f"\\nextgroupplot[{legend}title={{{title}}}]\n"
        f"\\addplot[black, line width=0.9pt] table[x=day, y=obs, col sep=comma] {{figures/data/fig_obspred_{k}.csv}};\n"
        f"\\addplot[pblue!45, line width=0.8pt] table[x=day, y=svr, col sep=comma] {{figures/data/fig_obspred_{k}.csv}};\n"
        f"\\addplot[pbluedark, line width=0.8pt] table[x=day, y=lgbh, col sep=comma] {{figures/data/fig_obspred_{k}.csv}};\n"
        f"\\addplot[black!45, densely dashed, line width=0.6pt] table[x=day, y=persist, col sep=comma] {{figures/data/fig_obspred_{k}.csv}};\n"
        + ("\\legend{Observed, SVR (forecast model), LightGBM + PM2.5 history, Persistence}\n" if k == '1' else ''))
obspred = (
    "% Generated by research_paper_draft3/reruns/make_figures_tex.py from review_extras (train.ipynb rerun).\n"
    "\\begin{tikzpicture}\n"
    "\\begin{groupplot}[group style={group size=1 by 2, vertical sep=17mm},\n"
    f"  width=\\textwidth, height=40mm, xmin=0, xmax=7, ymin=0, ymax={ymax:.0f}, xtick={{0,...,7}},\n"
    "  xlabel={Days from start of week}, ylabel={PM2.5 (\\ugm)}, label style={font=\\scriptsize},\n"
    "  tick label style={font=\\scriptsize}, title style={font=\\scriptsize\\bfseries, text=pbluedark},\n"
    "  ymajorgrids, grid style={black!15}, axis x line*=bottom, axis y line*=left, unbounded coords=jump]\n"
    + ''.join(panels) +
    "\\end{groupplot}\n\\end{tikzpicture}\n\n\\ref{oplegend}\n")
(FIG / 'fig_obspred.tex').write_text(obspred)

# ------------------------------------------------- PNG copies for the docx build
# A full page (so the named legend works), compiled twice, cropped, then rasterised.
preamble = (
    "\\documentclass[border=6pt,varwidth=19cm]{standalone}\n"
    "\\usepackage{pgfplots}\\usepgfplotslibrary{groupplots}\n"
    "\\pgfplotsset{compat=newest}\\usepackage{textcomp}\n"
    "\\definecolor{pblue}{cmyk}{1,0.3,0,0.2}\\colorlet{pbluedark}{pblue!60!black}\n"
    "\\newcommand{\\ugm}{\\textmu{}g/m\\textsuperscript{3}}\n")
for name in ('fig_eda', 'fig_obspred'):
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        shutil.copytree(FIG / 'data', tmp / 'figures' / 'data')
        body = (FIG / f'{name}.tex').read_text()
        (tmp / 'f.tex').write_text(preamble + "\\begin{document}\n\\centering\n\\textwidth=17.5cm\n" + body + "\n\\end{document}\n")
        for _ in range(2):
            subprocess.run(['pdflatex', '-interaction=nonstopmode', '-halt-on-error', 'f.tex'], cwd=tmp,
                           check=True, capture_output=True)
        subprocess.run(['pdftoppm', '-png', '-r', '220', '-singlefile', 'f.pdf', 'f'], cwd=tmp, check=True)
        shutil.copy(tmp / 'f.png', DOCX_FIG / f'{name}.png')
print('wrote fig_eda.tex, fig_obspred.tex and their PNG copies')
